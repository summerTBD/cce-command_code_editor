//! 语言服务器（LSP）客户端 —— lsp/ 的职责
//!
//! ## 我们只当「话务员」
//!
//! 这个模块**一行分析逻辑都没有**，也永远不会有。语法检查、类型推断、借检查
//! —— 全部是服务器（rust-analyzer）的事。
//!
//! 我们负责的只有四件事：**把话问到、把话收回来、搞清楚谁在跟谁说话、
//! 把结果交出去**。LSP 这个协议存在的全部理由就是让编辑器**不必**自己写分析器
//! （在它之前，每个编辑器都要给每种语言各写一份），所以我们绝不越过这条线。
//!
//! ## 里有什么
//!
//! - [`framing`]：Base Protocol —— 给消息套一个 `Content-Length` 长度头。
//!   **纯字节**，是整个模块里唯一能拿「金标准」逐字节测的东西。
//! - [`message`]：JSON-RPC 2.0 —— 那段字节到底在说什么。
//!   同样是纯的：一段文本进，一个枚举出。
//! - [`client`]：唯一**不纯**的一层 —— 进程、两根管道、两个线程、状态机。
//! - [`session`]：再往上一层，把「客户端」和「屏幕上现在是什么」绑在一起 ——
//!   换文件发 `didOpen`、改了字发 `didChange`、一个字没动就什么都不发。
//! - [`pool`]：最外面一层，按**项目根**存放会话 —— 服务器是认根的（一个实例
//!   只管一个 crate 图），所以打开另一个项目的文件就得再起一个，
//!   而这个池子负责「最多留几个、淘汰谁」。
//! - [`uri`]：路径 ↔ `file://`。纯函数，但它解决的是一件很脏的事：
//!   实测服务器会把盘符规范成小写，所以「两个 uri 是不是同一个文件」
//!   不能拿字符串相等去判。
//!
//! ## 里没有什么（以及为什么）
//!
//! - **不持有进程**。进程、线程、通道都是「活着的东西」，归 `main.rs` 的主循环。
//!   `App` 里也只存诊断**数据**，不存客户端 —— 跟 `run_action` 不拿终端、
//!   `check.rs` 不碰主循环是同一个立场：**一旦让纯状态沾上活物，整套测试就没了**。
//! - **不碰终端**。它连「现在是哪个模式」都不知道。
//! - **不认识 `App`**。诊断类型在 `diagnostic.rs`，谁都能用，谁都不欠谁。

pub mod client;
pub mod diagnostics;
pub mod framing;
pub mod message;
pub mod pool;
pub mod session;
pub mod uri;
