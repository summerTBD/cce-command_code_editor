//! 「工具路线」—— 起一个子进程，文本喂进去，文本拿回来。
//!
//! ## 这个目录是**一条接缝**，不是「来一个外部程序就加一个文件」的筐
//!
//! 判据是**形状**，不是数量：
//!
//! | | 这一条（本目录） | 那一条（[`crate::lsp`]） |
//! |---|---|---|
//! | 进程 | 起一次、干完就死 | **常驻** |
//! | 说话 | 单向：喂进去、拿回来 | **双向**：它也能主动找我们 |
//! | 协议 | 整份文本 | 结构化消息（有名字、有字段） |
//! | 例子 | `rustfmt`、`clang-format`、`cargo check` | `rust-analyzer`、`clangd` |
//!
//! ⚠️ **两条路线分开住，正因为它们本来就不一样。** 把 `lsp/` 也塞进这个目录
//! 会让两条不同的接缝看起来像一条 —— 而「别让不同的东西长成一个样子」
//! 恰恰是这个目录存在的理由。
//!
//! ## 加东西的时候往哪放
//!
//! - **再加一个格式化工具**（gofmt、prettier……）→ 加进
//!   [`formatter::PROVIDERS`] 那张表。**本目录一个文件都不会多。**
//! - **「一次性子进程、文本进文本出」的另一个用途**（lint、diff……）→
//!   在这里新开一个文件。但**先问一句**：它要的是不是「精确到行的结果」？
//!   是的话它其实属于协议路线 —— 那边的东西（[`crate::diagnostic`]）已经有了。
//! - **别把「一次性的活儿」写成常驻进程**，也别反过来。两条路线各自的代价
//!   不一样：这条便宜、但不能「边打边问」；那条能，但要管进程的一生。
//!
//! ## 为什么它们原来散在 `src/` 里
//!
//! 因为它们曾经只是「两个特例」。现在它们是一条**路线**了，就该有个名字 ——
//! 而这个目录名是个**断言**：以后每加一样东西，都得先回答「它属于哪条路线」。

