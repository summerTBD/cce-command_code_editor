//! 假的 LSP 服务器在测试里的**等待上限**。
//!
//! ## 这个常量解决的是什么
//!
//! `lsp_session` / `lsp_pool` / `lsp_client` 里那些等待助手，都需要一个「最多等多久」。
//! 一开始每个地方都直接写 `10` 秒，看着挺慷慨 —— 单个测试平时跑完只要 0.35 秒，
//! 快了将近 30 倍。
//!
//! **但它还是不稳定的。** 实测出现过一次 `wait_for_log("didOpen")` 超时：
//! 那一轮 `cargo test` 正好在并行跑 9 个起子进程的测试（每个还都带一个假服务器），
//! 机器上另外还开着一个 VS Code 和它的 `rust-analyzer` 在索引。那种情况下
//! **子进程可能很久都排不上 CPU** —— 我们这边 `didOpen` 早就写出去了，
//! 对面还没来得及读。
//!
//! ## 为什么「放宽」不是「把测试改软」
//!
//! 这个上限**不是断言**，是**防挂死的安全网**。它和真正被测的性质没关系：
//!
//! - 断言是「日志里有没有那一行」「顺序对不对」—— 一个字都没动
//! - 上限只决定「等不到时是失败还是多等一会儿」
//!
//! 所以放宽它不会让测试变得更容易通过 —— 只会让**机器忙**这件事不再伪装成
//! 被测代码的 bug。反过来说，一个会随机变红的测试比一个失败的测试更糟：
//! 它会让人开始怀疑「绿了也可能没好」，那正是这套测试存在的意义。
//!
//! ## 为什么不是「串行跑」
//!
//! 也可以让这些测试互相排队（一个共享的锁）。代价是整套测试慢下来，
//! 而且那个锁本身也要解释。等待上限更简单，而且它本来就是干这个的。

use std::time::Duration;

/// 等假服务器说一句话，最多等这么久。
///
/// 平时 0.35 秒就跑完 —— 这个数字只在机器被压住的时候才用得上。
pub const FAKE_SERVER_WAIT: Duration = Duration::from_secs(60);
